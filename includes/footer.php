function formatIndianNumber(x) {
  x = x.toString();
  let lastThree = x.substring(x.length - 3);
  let otherNumbers = x.substring(0, x.length - 3);

  if (otherNumbers !== '') {
    lastThree = ',' + lastThree;
    otherNumbers = otherNumbers.replace(/\B(?=(\d{2})+(?!\d))/g, ",");
  }
  return otherNumbers + lastThree;
}

function animateCounter(element, duration = 3000) {
  const target = +element.getAttribute('data-value');
  const start = 0;
  const startTime = performance.now();

  function updateCounter(currentTime) {
    const elapsed = currentTime - startTime;
    const progress = Math.min(elapsed / duration, 1);
    const currentValue = Math.floor(progress * (target - start) + start);

    // Apply Indian formatting
    element.textContent = formatIndianNumber(currentValue);

    if (progress < 1) {
      requestAnimationFrame(updateCounter);
    } else {
      element.textContent = formatIndianNumber(target);
    }
  }

  requestAnimationFrame(updateCounter);
}

document.addEventListener('DOMContentLoaded', () => {
  const observer = new IntersectionObserver((entries, obs) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        const el = entry.target;
        if (!el.classList.contains('counted')) {
          el.classList.add('counted');
          animateCounter(el);
        }
        obs.unobserve(el);
      }
    });
  }, {
    threshold: 0.6,
  });

  document.querySelectorAll('.counter').forEach(counter => {
    observer.observe(counter);
  });
});


